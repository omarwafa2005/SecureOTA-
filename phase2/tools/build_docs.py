#!/usr/bin/env python3
"""Render trace/*.csv and the authorization matrix into docs/generated/*.md.

Usage:
  python tools/build_docs.py           write the generated tables
  python tools/build_docs.py --check   exit 1 if any generated table is out of date

The CSV files are the source of truth; never edit docs/generated/ by hand.
"""
from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from oem_backend.auth import AUTHZ_MATRIX, ROLES  # noqa: E402

OUT = ROOT / "docs" / "generated"
HEADER = "<!-- Generated by tools/build_docs.py from {src}. Do not edit by hand. -->\n\n"
TEST_RE = re.compile(r'def (test_\w+)\(self\):\s*"""\s*((?:ACC|AT|FT|QT|E2E)-\d{2}[a-z]?)\s*\|\s*([^|]*)\|\s*([^"\n]*)')


def read(name):
    with open(ROOT / "trace" / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def cell(v) -> str:
    return str(v).replace("|", ", ").replace("\n", " ")


def table(rows, cols, titles=None) -> str:
    titles = titles or cols
    out = ["| " + " | ".join(titles) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(cell(r[c]) for c in cols) + " |" for r in rows]
    return "\n".join(out) + "\n"


def requirements() -> str:
    reqs = read("requirements.csv")
    names = {"FR": "Functional", "SR": "Security", "SAF": "Safety and resilience",
             "NFR": "Quality", "PR": "Privacy", "US": "Usability"}
    must = sum(r["priority"] == "Must" for r in reqs)
    parts = [f"# Requirements catalog\n\n{len(reqs)} requirements, {must} Must. "
             "Status Draft = guide baseline refined by the team; Proposed = team addition "
             "that needs supervisor approval.\n"]
    for prefix, name in names.items():
        rows = [r for r in reqs if r["class"] == prefix]
        parts.append(f"\n## {name} ({prefix})\n\n")
        parts.append(table(rows, ["id", "statement", "priority", "owner", "reviewer", "source",
                                  "component", "tests", "status"],
                           ["ID", "Statement", "Priority", "Owner", "Reviewer", "Source",
                            "Component", "Tests", "Status"]))
    return "".join(parts)


def risks() -> str:
    threats = sorted(read("threats.csv"), key=lambda t: (-int(t["score"]), t["id"]))
    counts = {}
    for t in threats:
        counts[t["class"]] = counts.get(t["class"], 0) + 1
    summary = ", ".join(f"{counts.get(c, 0)} {c}" for c in ("Critical", "High", "Medium", "Low"))
    out = [f"# Prioritized risk register\n\n{len(threats)} entries: {summary}. "
           "Risk = Likelihood x Impact (1-5 each). Sorted by score.\n\n## Summary\n\n"]
    out.append(table(threats, ["id", "title", "stride", "asset", "likelihood", "impact", "score",
                               "class", "owner", "tests"],
                     ["ID", "Threat or fault", "STRIDE", "Asset", "L", "I", "Score", "Class",
                      "Owner", "Tests"]))
    out.append("\n## Rationale and treatment\n")
    for t in threats:
        out.append(f"\n### {t['id']} {t['title']} - {t['score']} {t['class']}\n\n"
                   f"- **Attacker / source:** {t['attacker']}\n"
                   f"- **Likelihood {t['likelihood']}:** {t['likelihood_rationale']}\n"
                   f"- **Impact {t['impact']}:** {t['impact_rationale']}\n"
                   f"- **Requirements:** {cell(t['requirements']) or '-'}\n"
                   f"- **Prevention:** {t['prevention'] or '-'}\n"
                   f"- **Detection:** {t['detection'] or '-'}\n"
                   f"- **Recovery:** {t['recovery'] or '-'}\n"
                   f"- **Negative tests:** {cell(t['tests']) or '-'}\n"
                   f"- **Residual risk:** {t['residual_risk'] or '-'}\n"
                   f"- **Status:** {t['status']}\n")
    return "".join(out)


def matrix() -> str:
    rows = read("traceability.csv")
    return ("# Master traceability matrix\n\nAsset -> Threat -> Risk -> Requirement -> Control -> "
            "Component -> Test -> Evidence. Rows with threat `-` trace a Must requirement that is "
            "not driven by a single threat.\n\n"
            + table(rows, ["asset_id", "threat_id", "risk_score", "requirement_id", "control",
                           "component", "test_id", "expected_result", "evidence_path", "status"],
                    ["Asset", "Threat", "Risk", "Requirement", "Control", "Component", "Test",
                     "Expected result", "Evidence", "Status"]))


def assets() -> str:
    rows = read("assets.csv")
    return ("# Asset inventory\n\n" + table(rows, ["id", "name", "owner", "location", "producer",
                                                   "consumers", "confidentiality", "integrity",
                                                   "availability", "worst_consequence",
                                                   "existing_protection", "planned_protection",
                                                   "requirements"],
                                            ["ID", "Asset", "Owner", "Location", "Producer",
                                             "Consumers", "C", "I", "A", "Worst credible consequence",
                                             "Existing protection", "Planned protection",
                                             "Requirements"]))


def standards() -> str:
    rows = read("standards.csv")
    return ("# Standards traceability matrix\n\nThis project is a simulation. Every row says the "
            "design is *informed by* or *mapped to* a public theme. No row claims certification, "
            "type approval or conformance. Where the team has not read the full text of a paid "
            "standard, the Access column says so.\n\n"
            + table(rows, ["id", "requirement_ids", "source", "theme", "relationship", "access",
                           "notes"],
                    ["ID", "Requirements", "Source", "Theme", "Relationship", "Access", "Notes"]))


def authorization() -> str:
    rows = []
    for action, allowed in AUTHZ_MATRIX.items():
        rows.append({"action": action, **{r: ("yes" if r in allowed else "") for r in ROLES}})
    note = ("\nAdditional rules: `approve_release` also requires approver != creator (SR-18); "
            "vehicle actions are limited to the caller's own vehicle_id (SR-08). Every action is "
            "audited with outcome SUCCESS, DENIED or FAILED (SR-09).\n")
    return ("# Authorization matrix\n\nSource: `oem_backend/auth.py` (AUTHZ_MATRIX). "
            "Anything not marked is denied.\n\n" + table(rows, ["action", *ROLES]) + note)


def tests() -> str:
    rows = []
    for path in sorted((ROOT / "tests").glob("test_*.py")):
        for m in TEST_RE.finditer(path.read_text(encoding="utf-8")):
            rows.append({"id": m.group(2), "threats": m.group(3).strip(),
                         "requirements": m.group(4).strip(), "file": f"tests/{path.name}",
                         "function": m.group(1)})
    order = {"ACC": 0, "AT": 1, "FT": 2, "QT": 3, "E2E": 4}
    rows.sort(key=lambda r: (order[r["id"].split("-")[0]], r["id"], r["function"]))
    kinds = ("ACC acceptance (positive), AT attack (negative), FT fault injection, "
             "QT quality, E2E end to end")
    return (f"# Test catalog\n\n{len(rows)} test functions. {kinds}.\n\n"
            + table(rows, ["id", "threats", "requirements", "file", "function"],
                    ["Test", "Threats", "Requirements", "File", "Function"]))


PAGES = {
    "requirements_catalog.md": ("trace/requirements.csv", requirements),
    "risk_register.md": ("trace/threats.csv", risks),
    "traceability_matrix.md": ("trace/traceability.csv", matrix),
    "asset_inventory.md": ("trace/assets.csv", assets),
    "standards_matrix.md": ("trace/standards.csv", standards),
    "authorization_matrix.md": ("oem_backend/auth.py", authorization),
    "test_catalog.md": ("tests/test_*.py", tests),
}


def main(argv) -> int:
    check = "--check" in argv
    stale = []
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (src, fn) in PAGES.items():
        text = HEADER.format(src=src) + fn()
        path = OUT / name
        if check:
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    if check:
        if stale:
            print("FAIL: out of date, run python tools/build_docs.py:", ", ".join(stale))
            return 1
        print(f"PASS: {len(PAGES)} generated tables are up to date")
        return 0
    print(f"written {len(PAGES)} tables to docs/generated/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
